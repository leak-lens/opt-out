#!/usr/bin/env node
// Validates every law file and bundles them into web/laws-data.js (window.LAWS_DATA).
const fs = require("fs");
const path = require("path");
const { spawnSync } = require("child_process");

const root = path.join(__dirname, "..");
const check = spawnSync(process.execPath, [path.join(__dirname, "validate.js")], { stdio: "inherit" });
if (check.status !== 0) {
  console.error("\nBuild aborted: fix validation errors first.");
  process.exit(1);
}

const lawsDir = path.join(root, "laws");
const laws = fs
  .readdirSync(lawsDir)
  .filter((f) => f.endsWith(".json"))
  .sort()
  .map((f) => JSON.parse(fs.readFileSync(path.join(lawsDir, f), "utf8")));

const out =
  "// GENERATED by scripts/build.js from laws/*.json. Do not edit by hand.\n" +
  "window.LAWS_DATA = " + JSON.stringify(laws) + ";\n";
fs.writeFileSync(path.join(root, "web", "laws-data.js"), out);
const jurisdictions = new Set(laws.flatMap((l) => l.jurisdictions));
console.log(`\nBuilt web/laws-data.js: ${laws.length} laws, ${jurisdictions.size} jurisdictions.`);
